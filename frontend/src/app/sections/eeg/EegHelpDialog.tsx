export type EegHelpDialogProps = {
  open: boolean
  onClose: () => void
}

export function EegHelpDialog({ open, onClose }: EegHelpDialogProps) {
  useEffect(() => {
    if (!open) return
    function onKeyDown(event: KeyboardEvent) {
      if (event.key === 'Escape') onClose()
    }
    window.addEventListener('keydown', onKeyDown)
    return () => window.removeEventListener('keydown', onKeyDown)
  }, [open, onClose])

  if (!open) return null

  return (
    <div
      data-testid="eeg-help-overlay"
      className="fixed inset-0 z-40 flex items-center justify-center bg-bg-0/70 p-6"
      onClick={onClose}
    >
      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby="eeg-help-title"
        data-testid="eeg-help-dialog"
        className="max-h-full w-full max-w-2xl overflow-y-auto rounded-xl border border-border bg-bg-1 p-5 shadow-2xl"
        onClick={(event) => event.stopPropagation()}
      >
        <div className="flex items-start gap-3">
          <h2 id="eeg-help-title" className="text-lg font-semibold text-fg-0">
            Как читать трек и спектрограмму
          </h2>
          <Button
            variant="ghost"
            className="ml-auto px-2 py-1"
            aria-label="Закрыть справку"
            icon={<X className="size-4" />}
            onClick={onClose}
          >
            Закрыть
          </Button>
        </div>

        <div className="mt-3 flex flex-col gap-3">
          {EEG_HELP_BLOCKS.map((block) => (
            <section key={block.title}>
              <h3 className="text-sm font-semibold text-fg-0">{block.title}</h3>
              <p className="mt-1 text-sm text-fg-2">{block.text}</p>
            </section>
          ))}
        </div>
      </div>
    </div>
  )
}

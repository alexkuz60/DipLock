/**
 * Статья «Экспорт записи: пакет (zip) и CSV»: зачем выгружать запись, шаги
 * (панель → формат → кнопка → скачивание), состав пакетов session и BIDS,
 * CSV диполей, кэш/квота и предупреждения.
 *
 * Числа и правила — из `docs/history.md` (04.10.2026, срез 4.6),
 * `docs/rules/data-and-caches.md` п.18 и кода `shared/ui/SessionExport.tsx` /
 * `backend/app/services/session_bundle.py`: статья объясняет правила, а не
 * изобретает их (правило `docs/rules/wiki.md`).
 */
import {
  ArticleTitle,
  Callout,
  H3,
  P,
  Step,
  Term,
  UiRef,
  Ul,
  WikiLink,
} from '../wikiUi'

export function SessionExportArticle() {
  return (
    <>
      <ArticleTitle
        lead={
          <>
            Панель <UiRef>Экспорт записи</UiRef> (раздел EDF, правая колонка) выгружает запись
            со всеми результатами: <b>пакет zip</b> — манифест версий, паспорт, параметры и
            результаты задач плюс сам EDF (форматы <b>session</b> и <b>BIDS</b>), и{' '}
            <b>CSV-таблицу диполей</b> всех сессий записи. Это способ забрать данные отсюда —
            для архива, коллеги или другой программы; сам архив —{' '}
            <Term id="bundle">пакет записи</Term>.
          </>
        }
      >
        Экспорт записи: пакет (zip) и CSV
      </ArticleTitle>

      <H3 id="why">Зачем экспортировать</H3>
      <Ul>
        <li>
          <b>Воспроизводимость.</b> Пакет несёт манифест (версии среды и отпечатки ассетов),
          паспорт и параметры/результаты задач: через год видно, <i>чем</i> считалось, а не только
          «что получилось»;
        </li>
        <li>
          <b>Передача в другие инструменты.</b> Формат BIDS — минимальная стандартная структура
          (EDF по BIDS-пути, сайдкары событий и метаданных), которую читают другие пакеты
          анализа;
        </li>
        <li>
          <b>Таблицы без расчёта.</b> CSV диполей скачивается прямой ссылкой — без задачи и
          ожидания, когда нужно просто открыть точки в таблицах.
        </li>
      </Ul>

      <H3 id="prepare">Шаги подготовки</H3>
      <Step n={1} title="Откройте запись в разделе EDF">
        <P>
          Экспорт работает по <b>открытой записи</b>: без неё панель честно говорит «Запись не
          загружена — экспортировать пока нечего». Порядок открытия — в{' '}
          <WikiLink to="open">«Шаг 0. Открытие записи»</WikiLink>.
        </P>
      </Step>
      <Step n={2} title="Выберите формат пакета">
        <P>
          Сегмент <b>«Формат пакета»</b>: <b>session</b> (EDF + результаты) или <b>bids</b>.
          Правка формата задачу <b>не запускает</b>, но сбрасывает ссылку на zip прежнего
          формата — иначе она вела бы на устаревший файл.
        </P>
      </Step>
      <Step n={3} title="«Собрать пакет (zip)» — обычная задача">
        <P>
          Кнопка запускает фоновую задачу: пилюля прогресса с процентом и этапом, отмена —
          кнопкой <UiRef>Отменить</UiRef>. Сборка потоковая (архив не держится в памяти целиком),
          одинаковые входы → тот же zip из кэша без пересборки.
        </P>
      </Step>
      <Step n={4} title="Скачайте zip и/или CSV">
        <P>
          С готовым результатом — пилюля «Готово: N МБ, файлов K», ссылка{' '}
          <b>«Скачать zip»</b> и подпись «формат …, отпечаток …». Ссылка{' '}
          <b>«Скачать таблицу диполей (CSV)»</b> живёт всегда, независимо от задачи.
        </P>
      </Step>

      <H3 id="formats">Что внутри пакетов</H3>
      <Ul>
        <li>
          <b>session</b> — <code>manifest.json</code> (версии среды, отпечатки ассетов),{' '}
          <code>passport.json</code> (паспорт записи с событиями), <code>jobs/*.json</code> —
          параметры и результаты задач — и сам EDF-файл;
        </li>
        <li>
          <b>bids</b> — <code>dataset_description.json</code>, <code>participants.tsv</code>,
          сайдкары <code>*_eeg.json</code> и <code>*_events.tsv</code> из паспорта, EDF по
          BIDS-пути; имя задачи — честный лейбл <code>task-unknown</code>, а не выдуманный
          «rest»;
        </li>
        <li>
          <b>CSV диполей</b> — все сессии записи одной таблицей (RFC 4180: CRLF, кавычки по
          необходимости, пустая ячейка вместо «нет значения»); открывается в любых таблицах.
        </li>
      </Ul>

      <H3 id="reading">Кэш, квота и предупреждения</H3>
      <Callout tone="info" title="Одинаковые входы — тот же zip">
        <p>
          Ключ пакета — входной отпечаток: формат, дайджест EDF, паспорт, список задач и версии
          ассетов. Пока входы не менялись, повторная сборка берёт архив из кэша (журнал запишет{' '}
          <code>cache_hit</code>) — это быстро и не тратит место. Файл живёт в{' '}
          <code>data/cache/bundles/</code> и чистится вместе с записью.
        </p>
      </Callout>
      <Callout tone="warn" title="Что пакет честно предупредит">
        <p>
          Пропавший EDF-файл — предупреждение в списке <b>warnings</b>, пакет собирается без
          данных, а не падает. Сами пакеты (задачи вида bundle) внутрь архива не входят —
          «архив не несёт сам себя». После очистки кэша ссылка на старый zip отдаёт 404 с
          просьбой «соберите пакет заново».
        </p>
      </Callout>
      <Callout tone="tip" title="Кэш записей и квота">
        <p>
          Сколько места занимают кэши, видно в разделе «Состояние сервера» — строка{' '}
          <b>«Кэш записей»</b> (прочерк означает «не посчиталось», а не «0 МБ»). Автоочистка по
          квоте (LRU) по умолчанию <b>выключена</b> (<code>CACHE_QUOTA_MB=0</code>) — включайте
          её осознанно: старые кэши удаляются до влезания в лимит, результаты задач при этом
          не трогаются.
        </p>
      </Callout>

      <H3 id="next">Что дальше</H3>
      <Ul>
        <li>
          <WikiLink to="open">«Шаг 0. Открытие записи»</WikiLink> — паспорт записи и реестр, из
          которого берутся кандидаты;
        </li>
        <li>
          <WikiLink to="summary-report">«Итоги: сквозной автоотчёт записи»</WikiLink> — что из
          результатов стоит собрать в документ <i>до</i> выгрузки;
        </li>
        <li>
          <WikiLink to="group-analysis">«Групповой анализ»</WikiLink> — оттуда же экспортируется
          агрегатная таблица (своя кнопка «Экспорт CSV»);
        </li>
        <li>
          вернуться к <WikiLink to="glossary">Глоссарию</WikiLink>.
        </li>
      </Ul>
    </>
  )
}

